-- A workspace holds one person's data: custom commands, notes, progress and target values.
CREATE TABLE workspace (
    id          VARCHAR2(36)   PRIMARY KEY,
    vars_json   VARCHAR2(4000) DEFAULT '{}' NOT NULL,
    created_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE custom_command (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id  VARCHAR2(36)   NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    phase         VARCHAR2(16)   NOT NULL,
    category      VARCHAR2(80)   NOT NULL,
    title         VARCHAR2(200)  NOT NULL,
    cmd           VARCHAR2(2000) NOT NULL,
    note          VARCHAR2(2000),
    tags          VARCHAR2(200)  NOT NULL,
    ports         VARCHAR2(400),
    source_title  VARCHAR2(200),
    source_url    VARCHAR2(1000),
    created_at    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT custom_command_phase_ck CHECK (phase IN ('recon', 'enum', 'access', 'privesc', 'lateral', 'web', 'post'))
);
CREATE INDEX custom_command_ws_ix ON custom_command (workspace_id);

-- Notes and progress refer to any command id: built-in ("e12") or custom ("w5").
CREATE TABLE entry_note (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id  VARCHAR2(36)   NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    entry_id      VARCHAR2(64)   NOT NULL,
    body          VARCHAR2(4000) NOT NULL,
    CONSTRAINT entry_note_uq UNIQUE (workspace_id, entry_id)
);

CREATE TABLE entry_progress (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id  VARCHAR2(36)   NOT NULL REFERENCES workspace (id) ON DELETE CASCADE,
    entry_id      VARCHAR2(64)   NOT NULL,
    CONSTRAINT entry_progress_uq UNIQUE (workspace_id, entry_id)
);
